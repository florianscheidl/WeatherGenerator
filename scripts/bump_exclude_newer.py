#!/usr/bin/env python3
# ruff: noqa: T201
"""Move the uv `exclude-newer` cutoff in pyproject.toml and report what changes.

uv.lock is not committed, so the cutoff decides which versions a fresh install gets.
This script moves it to a date `--lag-days` in the past (or to `--cutoff`), resolves
the workspace before and after with `uv lock --upgrade`, and writes a Markdown summary
with the version changes. The scheduled workflow
.github/workflows/bump_exclude_newer.yml uses the summary as the pull request text.

Exit codes: 0 when the cutoff moved and resolves, or when there is nothing to do;
3 when the new cutoff does not resolve (the pyproject.toml change is kept and the
summary contains uv's error). An existing uv.lock is restored at the end.
"""

import argparse
import datetime as dt
import re
import subprocess
import sys
import tomllib
from pathlib import Path

PYPROJECT = Path("pyproject.toml")
LOCKFILE = Path("uv.lock")
CUTOFF_LINE = re.compile(r'^exclude-newer = "(?P<date>[^"]+)"$', re.MULTILINE)


def read_cutoff(text: str) -> str:
    """Return the current cutoff string of the [tool.uv] table."""
    matches = CUTOFF_LINE.findall(text)
    if len(matches) != 1:
        raise SystemExit(f"Expected one 'exclude-newer = \"...\"' line, found {len(matches)}.")
    return matches[0]


def new_cutoff(requested: str | None, lag_days: int, today: dt.date) -> str:
    """Return the new cutoff as an RFC 3339 timestamp at midnight UTC."""
    if requested:
        day = dt.date.fromisoformat(requested)
    else:
        day = today - dt.timedelta(days=lag_days)
    return f"{day.isoformat()}T00:00:00Z"


def lock_versions() -> tuple[dict[str, str] | None, str]:
    """Resolve from scratch and return ({package: versions}, uv output)."""
    LOCKFILE.unlink(missing_ok=True)
    result = subprocess.run(["uv", "lock", "--upgrade"], capture_output=True, text=True)
    output = (result.stdout + result.stderr).strip()
    if result.returncode != 0:
        return None, output
    packages: dict[str, set[str]] = {}
    for package in tomllib.loads(LOCKFILE.read_text())["package"]:
        packages.setdefault(package["name"], set()).add(package.get("version", "?"))
    return {name: ", ".join(sorted(v)) for name, v in packages.items()}, output


def changes_table(old: dict[str, str], new: dict[str, str]) -> list[str]:
    """Return Markdown table rows for every package whose versions differ."""
    rows = ["| Package | Before | After |", "|---|---|---|"]
    for name in sorted(old.keys() | new.keys()):
        if old.get(name) != new.get(name):
            rows.append(f"| {name} | {old.get(name, '–')} | {new.get(name, '–')} |")
    return rows


def write_outputs(path: str | None, **values: str) -> None:
    """Append key=value lines for GitHub Actions step outputs, if requested."""
    if path:
        with open(path, "a") as f:
            for key, value in values.items():
                f.write(f"{key}={value}\n")


def main() -> int:
    """Run the bump and leave any existing uv.lock as it was."""
    saved_lock = LOCKFILE.read_bytes() if LOCKFILE.exists() else None
    try:
        return bump()
    finally:
        if saved_lock is None:
            LOCKFILE.unlink(missing_ok=True)
        else:
            LOCKFILE.write_bytes(saved_lock)


def bump() -> int:
    """Move the cutoff, resolve before and after, and write the summary."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--cutoff", help="New cutoff date YYYY-MM-DD (default: today - lag).")
    parser.add_argument("--lag-days", type=int, default=14)
    parser.add_argument("--summary", type=Path, default=Path("bump_summary.md"))
    parser.add_argument("--github-output", help="File to append step outputs to.")
    args = parser.parse_args()

    text = PYPROJECT.read_text()
    old = read_cutoff(text)
    new = new_cutoff(args.cutoff, args.lag_days, dt.datetime.now(dt.UTC).date())
    if new <= old:
        print(f"Cutoff {old} is not older than {new}; nothing to do.")
        write_outputs(args.github_output, changed="false", old=old, new=new)
        return 0

    before, output = lock_versions()
    if before is None:
        raise SystemExit(f"The current cutoff {old} does not resolve:\n{output}")
    PYPROJECT.write_text(CUTOFF_LINE.sub(f'exclude-newer = "{new}"', text))
    after, output = lock_versions()

    lines = [
        f"Moves the uv `exclude-newer` cutoff from `{old}` to `{new}`.",
        "",
        "uv.lock is not committed, so this decides which versions a fresh install gets.",
        "Generated by `scripts/bump_exclude_newer.py`.",
        "",
    ]
    if after is None:
        lines += ["**The new cutoff does not resolve.** uv says:", "", "```", output, "```"]
        status = "unresolved"
    else:
        rows = changes_table(before, after)
        lines += [f"{len(rows) - 2} of {len(after)} packages change:", "", *rows]
        status = "resolved"
    args.summary.write_text("\n".join(lines) + "\n")
    write_outputs(args.github_output, changed="true", old=old, new=new, status=status)
    print(f"{old} -> {new}: {status}; summary in {args.summary}")
    return 0 if after is not None else 3


if __name__ == "__main__":
    sys.exit(main())
